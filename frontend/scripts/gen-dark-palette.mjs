// Generates src/styles/palette-dark.css: Tailwind's colour scales re-pointed for
// the dark theme. Run after a Tailwind upgrade: node scripts/gen-dark-palette.mjs
//
// Tailwind v4 utilities read their colours from --color-* variables, so
// redefining the variables under [data-theme="dark"] re-themes every bg-/text-/
// border-/ring-/hover: utility in the app at once - including the ones the old
// hand-written override list never covered (hover:bg-slate-100 turned light
// grey on hover, bg-amber-50 notices stayed bright yellow, a black toner bar
// vanished into the dark card).
//
//  - neutral scales (slate, gray, zinc, neutral, stone) are inverted onto one
//    graphite ramp: 50-100 become raised surfaces, 400-600 muted text,
//    800-950 the strongest ink;
//  - hue scales keep 400-500 (fills, dots, toner bars) and swap the ends:
//    50-300 become tinted dark grounds and borders, 600-950 light ink.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const themeCss = readFileSync(resolve(here, "../node_modules/tailwindcss/theme.css"), "utf8");
const colors = {};
for (const m of themeCss.matchAll(/--color-([a-z]+)-(\d+):\s*([^;]+);/g)) {
  (colors[m[1]] ??= {})[m[2]] = m[3].trim();
}

const NEUTRALS = ["slate", "gray", "zinc", "neutral", "stone"];
const HUES = Object.keys(colors).filter((name) => !NEUTRALS.includes(name));

// Graphite ramp, matched to the surface tokens in tokens.css.
const NEUTRAL_RAMP = {
  50: "#1b1f26",
  100: "#222730",
  200: "#2c323c",
  300: "#3b424e",
  400: "#6e7785",
  500: "#8d95a3",
  600: "#a4acb9",
  700: "#c0c6d0",
  800: "#d8dce3",
  900: "#eaedf1",
  950: "#f5f6f8",
};

// The ground hue tints are mixed onto (= --surface-1 in dark).
const GROUND = "#15181e";
const TINT = { 50: 10, 100: 16, 200: 28, 300: 42 };
const LIGHT_INK = { 600: "400", 700: "300", 800: "200", 900: "100", 950: "50" };

const lines = [];
lines.push("/* GENERATED by scripts/gen-dark-palette.mjs - do not edit by hand. */");
lines.push("");
lines.push(':root[data-theme="dark"] {');
for (const name of NEUTRALS) {
  if (!colors[name]) continue;
  for (const [step, value] of Object.entries(NEUTRAL_RAMP)) {
    lines.push(`  --color-${name}-${step}: ${value};`);
  }
}
for (const name of HUES) {
  const scale = colors[name];
  if (!scale["500"]) continue;
  for (const [step, pct] of Object.entries(TINT)) {
    lines.push(`  --color-${name}-${step}: color-mix(in oklab, ${scale["500"]} ${pct}%, ${GROUND});`);
  }
  for (const [step, from] of Object.entries(LIGHT_INK)) {
    lines.push(`  --color-${name}-${step}: ${scale[from]};`);
  }
}
lines.push("}");
lines.push("");

writeFileSync(resolve(here, "../src/styles/palette-dark.css"), lines.join("\n"));
console.log(`palette-dark.css: ${NEUTRALS.length} neutral + ${HUES.length} hue scales`);
